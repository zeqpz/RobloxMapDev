"""Chopped export of a kit-built block (run in Blender after the block script built the scene).

exec(open(r"<repo>/blender/bexport.py").read())   with  BX_BLOCK = "WG01"
Writes exports/westgate/<block>/:
  <block>_<Building>.fbx   one per building; every object = one piece x one material, at world position
                           (object name  <block>_<Building>.<Piece>__<RobloxMaterial>_<HEX>)
  <block>_Protos.fbx       every prototype (doors, windows, ...) once, at the origin  (P.<proto>__<Material>_<HEX>)
  <block>_Placements.lua   ModuleScript source: {proto, piece, cf = {x, y, z, yaw}} in ROBLOX coordinates
  manifest.json            counts per building / piece / prototype (for the installer + review)
Studio side: studio/westgate/InstallBlock.lua groups the imported MeshParts into one Model per piece, applies
Material + Color from the names, sets collision/shadows, and clones the prototypes into place.
"""
import json
import math
import os
import sys
from collections import defaultdict

import bpy

REPO = r"C:\Users\CooperHinkel\Documents\ClaudeRoblox\RobloxMapDev"
sys.path.append(os.path.join(REPO, "blender"))
import importlib
import rmd_kit as rk
importlib.reload(rk)

BLOCK = globals().get("BX_BLOCK", "WG01")
OUTD = os.path.join(REPO, "exports", "westgate", BLOCK.lower())
os.makedirs(OUTD, exist_ok=True)
sc = bpy.data.scenes[BLOCK]

manifest = dict(block=BLOCK, buildings={}, protos={}, placements=0)
placements = []
# ------------------------------------------------------------------ buildings (shell pieces)
for c in sc.collection.children:
    if not c.name.startswith(BLOCK + "_") or c.name.endswith(("_Context", "_Protos")):
        continue
    bldg = c.name[len(BLOCK) + 1:]
    shell = [o.name for o in c.objects if o.type == "MESH"]
    pieces = defaultdict(int)
    for n in shell:
        pieces[n.split("__")[0].split(".", 1)[1]] += 1
    if shell:
        rk.export_fbx(os.path.join(OUTD, f"{BLOCK}_{bldg}.fbx"), shell, apply_modifiers=False)
    # instances -> placements (one per proto per transform)
    seen = set()
    for sub in c.children:
        for o in sub.objects:
            proto = o.get("proto")
            if not proto:
                continue
            m = o.matrix_world
            key = (proto, tuple(round(v, 3) for v in m.translation), round(m.to_euler().z, 4))
            if key in seen:
                continue
            seen.add(key)
            x, y, z = m.translation
            yaw = m.to_euler().z
            placements.append(dict(proto=proto, piece=o.get("piece", ""), x=round(x, 3), y=round(z, 3), z=round(-y, 3),
                                   yaw=round(yaw, 5)))
    manifest["buildings"][bldg] = dict(objects=len(shell), pieces=dict(pieces),
                                       instances=sum(1 for p in placements if p["piece"].startswith(f"{BLOCK}_{bldg}.")))
# ------------------------------------------------------------------ prototypes
pc = bpy.data.collections.get(f"{BLOCK}_Protos")
proto_objs = [o.name for o in pc.objects] if pc else []
if proto_objs:
    lc = sc.view_layers[0].layer_collection.children.get(pc.name)
    hv = pc.hide_viewport
    pc.hide_viewport = False
    if lc:
        lc.exclude = False
    bpy.context.view_layer.update()
    rk.export_fbx(os.path.join(OUTD, f"{BLOCK}_Protos.fbx"), proto_objs, apply_modifiers=False)
    pc.hide_viewport = hv
    for n in proto_objs:
        ob = bpy.data.objects[n]
        manifest["protos"].setdefault(ob["proto"], 0)
        manifest["protos"][ob["proto"]] += sum(len(p.vertices) - 2 for p in ob.data.polygons)
manifest["placements"] = len(placements)
# ------------------------------------------------------------------ placements module (Roblox coordinates)
lines = ["-- generated by blender/bexport.py: prototype placements for " + BLOCK + " (Roblox world coordinates)",
         "-- cf = CFrame.new(x, y, z) * CFrame.Angles(0, yaw, 0)", "return {"]
for p in placements:
    lines.append(f'\t{{proto = "{p["proto"]}", piece = "{p["piece"]}", x = {p["x"]}, y = {p["y"]}, z = {p["z"]}, yaw = {p["yaw"]}}},')
lines.append("}")
open(os.path.join(OUTD, f"{BLOCK}_Placements.lua"), "w").write("\n".join(lines))
open(os.path.join(OUTD, "manifest.json"), "w").write(json.dumps(manifest, indent=1))
print(json.dumps({k: (v if k != "buildings" else {b: {"objects": d["objects"], "pieces": len(d["pieces"]), "instances": d["instances"]} for b, d in v.items()})
                  for k, v in manifest.items() if k != "protos"}, indent=1), "protos:", len(manifest["protos"]))
